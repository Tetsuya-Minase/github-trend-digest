/// Domain entities representing the core business objects.
///
/// These entities are immutable and contain validation logic
/// to ensure data integrity throughout the application lifecycle.
use serde::{Deserialize, Serialize};

/// Represents a GitHub repository with its metadata.
///
/// # Fields
/// - `name`: Repository name
/// - `owner`: Repository owner/organization name
/// - `url`: Full URL to the repository
/// - `description`: Optional repository description
/// - `stars`: Number of stars the repository has received
/// - `language`: Primary programming language
/// - `topics`: List of repository topics/tags
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Repository {
    name: String,
    owner: String,
    url: String,
    description: Option<String>,
    stars: u32,
    language: Option<String>,
    topics: Vec<String>,
}

impl Repository {
    /// Creates a new Repository instance with validation.
    ///
    /// # Arguments
    /// - `name`: Repository name (must not be empty)
    /// - `owner`: Repository owner (must not be empty)
    /// - `url`: Repository URL (must not be empty and should be a valid URL)
    /// - `description`: Optional description
    /// - `stars`: Star count
    /// - `language`: Optional primary language
    /// - `topics`: List of topics (will be deduplicated)
    ///
    /// # Returns
    /// - `Ok(Repository)` if all validations pass
    /// - `Err(String)` with error message if validation fails
    ///
    /// # Examples
    /// ```
    /// use github_trending_summary::domain::entities::Repository;
    ///
    /// let repo = Repository::new(
    ///     "rust".to_string(),
    ///     "rust-lang".to_string(),
    ///     "https://github.com/rust-lang/rust".to_string(),
    ///     Some("Empowering everyone to build reliable and efficient software.".to_string()),
    ///     80000,
    ///     Some("Rust".to_string()),
    ///     vec!["compiler".to_string(), "rust".to_string()],
    /// );
    /// assert!(repo.is_ok());
    /// ```
    pub fn new(
        name: String,
        owner: String,
        url: String,
        description: Option<String>,
        stars: u32,
        language: Option<String>,
        topics: Vec<String>,
    ) -> Result<Self, String> {
        // Validate name
        if name.trim().is_empty() {
            return Err("Repository name cannot be empty".to_string());
        }

        // Validate owner
        if owner.trim().is_empty() {
            return Err("Repository owner cannot be empty".to_string());
        }

        // Validate URL
        if url.trim().is_empty() {
            return Err("Repository URL cannot be empty".to_string());
        }
        if !url.starts_with("http://") && !url.starts_with("https://") {
            return Err("Repository URL must start with http:// or https://".to_string());
        }

        // Deduplicate topics while preserving order
        let mut seen = std::collections::HashSet::new();
        let topics: Vec<String> = topics
            .into_iter()
            .filter(|topic| seen.insert(topic.clone()))
            .collect();

        Ok(Self {
            name,
            owner,
            url,
            description,
            stars,
            language,
            topics,
        })
    }

    /// Returns the repository name.
    pub fn name(&self) -> &str {
        &self.name
    }

    /// Returns the repository owner.
    pub fn owner(&self) -> &str {
        &self.owner
    }

    /// Returns the repository URL.
    pub fn url(&self) -> &str {
        &self.url
    }

    /// Returns the repository description.
    pub fn description(&self) -> Option<&str> {
        self.description.as_deref()
    }

    /// Returns the number of stars.
    pub fn stars(&self) -> u32 {
        self.stars
    }

    /// Returns the primary programming language.
    pub fn language(&self) -> Option<&str> {
        self.language.as_deref()
    }

    /// Returns the repository topics.
    pub fn topics(&self) -> &[String] {
        &self.topics
    }

    /// Returns the full repository identifier (owner/name format).
    pub fn full_name(&self) -> String {
        format!("{}/{}", self.owner, self.name)
    }
}

/// Represents a summary of a trending repository generated by AI.
///
/// # Fields
/// - `repository`: The repository being summarized
/// - `ai_summary`: AI-generated summary of the repository
/// - `use_cases`: List of potential use cases
/// - `target_languages`: Programming languages targeted by this repository
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TrendingSummary {
    repository: Repository,
    ai_summary: String,
    use_cases: Vec<String>,
    target_languages: Vec<String>,
}

impl TrendingSummary {
    /// Creates a new TrendingSummary instance with validation.
    ///
    /// # Arguments
    /// - `repository`: The repository being summarized
    /// - `ai_summary`: AI-generated summary (must not be empty)
    /// - `use_cases`: List of use cases
    /// - `target_languages`: List of target languages
    ///
    /// # Returns
    /// - `Ok(TrendingSummary)` if all validations pass
    /// - `Err(String)` with error message if validation fails
    ///
    /// # Examples
    /// ```
    /// use github_trending_summary::domain::entities::{Repository, TrendingSummary};
    ///
    /// let repo = Repository::new(
    ///     "rust".to_string(),
    ///     "rust-lang".to_string(),
    ///     "https://github.com/rust-lang/rust".to_string(),
    ///     None,
    ///     80000,
    ///     Some("Rust".to_string()),
    ///     vec![],
    /// ).unwrap();
    ///
    /// let summary = TrendingSummary::new(
    ///     repo,
    ///     "A systems programming language.".to_string(),
    ///     vec!["System programming".to_string()],
    ///     vec!["Rust".to_string()],
    /// );
    /// assert!(summary.is_ok());
    /// ```
    pub fn new(
        repository: Repository,
        ai_summary: String,
        use_cases: Vec<String>,
        target_languages: Vec<String>,
    ) -> Result<Self, String> {
        // Validate AI summary
        if ai_summary.trim().is_empty() {
            return Err("AI summary cannot be empty".to_string());
        }

        Ok(Self {
            repository,
            ai_summary,
            use_cases,
            target_languages,
        })
    }

    /// Returns the repository.
    pub fn repository(&self) -> &Repository {
        &self.repository
    }

    /// Returns the AI-generated summary.
    pub fn ai_summary(&self) -> &str {
        &self.ai_summary
    }

    /// Returns the use cases.
    pub fn use_cases(&self) -> &[String] {
        &self.use_cases
    }

    /// Returns the target languages.
    pub fn target_languages(&self) -> &[String] {
        &self.target_languages
    }
}

